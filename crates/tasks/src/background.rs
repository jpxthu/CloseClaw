/// Manages the full lifecycle of background tasks.
pub struct BackgroundTaskManager {
    tasks: TaskMap,
    pub(crate) temp_dir: PathBuf,
    notifications: Arc<Mutex<Vec<CompletionNotification>>>,
    /// Maximum total execution time in seconds per task.
    /// Tasks exceeding this limit are force-killed.
    pub(crate) max_execution_secs: u64,
    /// Optional debug-log instance for structured event emission.
    debug_log: Option<Arc<DebugLog>>,
}

impl Default for BackgroundTaskManager {
    fn default() -> Self {
        Self {
            tasks: Arc::new(Mutex::new(HashMap::new())),
            temp_dir: PathBuf::from("/tmp"),
            notifications: Arc::new(Mutex::new(Vec::new())),
            max_execution_secs: 1800,
            debug_log: None,
        }
    }
}

impl BackgroundTaskManager {
    /// Create a new manager using the default temp root (`/tmp`).
    pub fn new() -> Self {
        Self::with_temp_dir("/tmp")
    }

    /// Create a new manager with an explicit temp root directory.
    pub fn with_temp_dir(temp_dir: impl Into<PathBuf>) -> Self {
        Self {
            tasks: Arc::new(Mutex::new(HashMap::new())),
            temp_dir: temp_dir.into(),
            notifications: Arc::new(Mutex::new(Vec::new())),
            max_execution_secs: 1800,
            debug_log: None,
        }
    }

    /// Create a new manager with a custom total execution time limit.
    ///
    /// `max_execution_secs` is the maximum total time (seconds) a task
    /// may run before being force-killed. Must be greater than the
    /// timeout parameter cap (600 s / 10 min).
    pub fn with_max_execution_secs(temp_dir: impl Into<PathBuf>, max_execution_secs: u64) -> Self {
        assert!(
            max_execution_secs > 600,
            "max_execution_secs ({}) must be greater than 600 (timeout parameter cap)",
            max_execution_secs
        );
        Self {
            tasks: Arc::new(Mutex::new(HashMap::new())),
            temp_dir: temp_dir.into(),
            notifications: Arc::new(Mutex::new(Vec::new())),
            max_execution_secs,
            debug_log: None,
        }
    }

    #[cfg(test)]
    pub(crate) fn with_max_execution_secs_unchecked(
        temp_dir: impl Into<PathBuf>,
        max_execution_secs: u64,
    ) -> Self {
        Self {
            tasks: Arc::new(Mutex::new(HashMap::new())),
            temp_dir: temp_dir.into(),
            notifications: Arc::new(Mutex::new(Vec::new())),
            max_execution_secs,
            debug_log: None,
        }
    }

    pub fn with_debug_log(mut self, debug_log: Arc<DebugLog>) -> Self {
        self.debug_log = Some(debug_log);
        self
    }

    fn emit_debug_event(
        &self,
        trace_id: &str,
        level: LogLevel,
        event_type: &str,
        payload: serde_json::Value,
    ) {
        emit_event(EmitEventParams {
            ctx: DebugLogContext::new(self.debug_log.as_deref(), trace_id, None),
            level,
            source_module: "tasks",
            event_type,
            payload,
            parent: None,
        });
    }
}

impl BackgroundTaskManager {
    /// Spawn a shell command in the background, returning immediately.
    pub async fn spawn(
        &self,
        command: &str,
        cwd: &Path,
        is_backgrounded: bool,
        session_id: &str,
    ) -> Result<BackgroundTask, BackgroundTaskError> {
        let task_id = Uuid::new_v4().to_string();
        let output_path = prepare_task_dir(&self.temp_dir, &task_id).await?;

        let trace_id = debug_log::generate_trace_id();

        insert_initial_handle(
            &self.tasks,
            &task_id,
            command,
            &output_path,
            is_backgrounded,
            session_id,
            &trace_id,
        )
        .await;

        tracing::info!(task_id = %task_id, command = %command, "background task started");
        self.emit_debug_event(
            &trace_id,
            LogLevel::Info,
            "background.task.started",
            serde_json::json!({"task_id": task_id, "command": command}),
        );

        stuck_detect::start_stuck_detection(
            task_id.clone(),
            output_path.clone(),
            command.to_owned(),
            Arc::clone(&self.tasks),
            Arc::clone(&self.notifications),
            StuckDetectConfig::default(),
        );

        let timeout_notify = {
            let map = lock_map(&self.tasks).await;
            map.get(&task_id)
                .map(|h| Arc::clone(&h.timeout_notify))
                .expect("handle must exist after insert")
        };

        let shared = Arc::clone(&self.tasks);
        let cmd = command.to_owned();
        let cwd = cwd.to_path_buf();
        let out = output_path.clone();
        let tid = task_id.clone();

        let notifs = Arc::clone(&self.notifications);
        let tn = Arc::clone(&timeout_notify);
        let dlog = self.debug_log.clone();

        tokio::spawn(async move {
            let ctx = ShellCommandContext {
                tasks: &shared,
                task_id: &tid,
                notifications: &notifs,
                timeout_notify: &tn,
                debug_log: dlog.as_deref(),
            };
            run_shell_command(&cmd, &cwd, &out, &ctx).await;
        });

        // Spawn the total-execution-time-limit monitor.
        let max_secs = self.max_execution_secs;
        let tid = task_id.clone();
        let shared = Arc::clone(&self.tasks);
        let notifs = Arc::clone(&self.notifications);
        let dlog = self.debug_log.clone();
        tokio::spawn(async move {
            spawn_max_execution_monitor(max_secs, &tid, &shared, &notifs, dlog.as_deref()).await;
        });

        Ok(make_public_task(
            &task_id,
            command,
            &output_path,
            is_backgrounded,
        ))
    }

    /// Take over a running child process.
    pub async fn backgroundize(
        &self,
        mut child: tokio::process::Child,
        command: &str,
        is_backgrounded: bool,
        session_id: &str,
    ) -> Result<BackgroundTask, BackgroundTaskError> {
        let task_id = Uuid::new_v4().to_string();
        let output_path = prepare_task_dir(&self.temp_dir, &task_id).await?;

        let stdout = child.stdout.take();
        let stderr = child.stderr.take();
        let trace_id = debug_log::generate_trace_id();
        insert_initial_handle(
            &self.tasks,
            &task_id,
            command,
            &output_path,
            is_backgrounded,
            session_id,
            &trace_id,
        )
        .await;
        tracing::info!(task_id = %task_id, command = %command, "background task started");
        self.emit_debug_event(
            &trace_id,
            LogLevel::Info,
            "background.task.started",
            serde_json::json!({"task_id": task_id, "command": command}),
        );

        stuck_detect::start_stuck_detection(
            task_id.clone(),
            output_path.clone(),
            command.to_owned(),
            Arc::clone(&self.tasks),
            Arc::clone(&self.notifications),
            StuckDetectConfig::default(),
        );

        let timeout_notify = {
            let map = lock_map(&self.tasks).await;
            map.get(&task_id)
                .map(|h| Arc::clone(&h.timeout_notify))
                .expect("handle must exist after insert")
        };

        let shared = Arc::clone(&self.tasks);
        let out = output_path.clone();
        let tid = task_id.clone();

        let notifs = Arc::clone(&self.notifications);
        let tn = Arc::clone(&timeout_notify);
        let dlog = self.debug_log.clone();

        tokio::spawn(async move {
            let ctx = BackgroundizeContext {
                tasks: &shared,
                task_id: &tid,
                notifications: &notifs,
                timeout_notify: &tn,
                debug_log: dlog.as_deref(),
            };
            backgroundize_process(child, stdout, stderr, &out, &ctx).await;
        });

        // Spawn the total-execution-time-limit monitor.
        let max_secs = self.max_execution_secs;
        let tid = task_id.clone();
        let shared = Arc::clone(&self.tasks);
        let notifs = Arc::clone(&self.notifications);
        let dlog = self.debug_log.clone();
        tokio::spawn(async move {
            spawn_max_execution_monitor(max_secs, &tid, &shared, &notifs, dlog.as_deref()).await;
        });

        Ok(make_public_task(
            &task_id,
            command,
            &output_path,
            is_backgrounded,
        ))
    }
}

impl BackgroundTaskManager {
    /// Send SIGKILL to a running task, transitioning to Killed.
    pub async fn kill(&self, task_id: &str) -> Result<(), BackgroundTaskError> {
        let mut map = lock_map(&self.tasks).await;
        let handle = map
            .get_mut(task_id)
            .ok_or_else(|| BackgroundTaskError::NotFound(task_id.to_owned()))?;

        if !matches!(handle.state, TaskState::Running { .. }) {
            return Err(BackgroundTaskError::NotRunning(task_id.to_owned()));
        }

        if let Some(kill_tx) = handle.kill_tx.take() {
            let _ = kill_tx.send(());
        }
        handle.state = TaskState::Killed;
        tracing::info!(task_id = %task_id, "background task killed");

        let trace_id = handle.trace_id.clone();
        if !trace_id.is_empty() {
            self.emit_debug_event(&trace_id, LogLevel::Info, "background.task.terminal",
                serde_json::json!({"task_id": task_id, "command": handle.command, "new_state": "killed"}));
        }
        Ok(())
    }

    /// Return `true` if the task is in the [`TaskState::Running`] state.
    pub async fn is_running(&self, task_id: &str) -> bool {
        let map = lock_map(&self.tasks).await;
        map.get(task_id)
            .is_some_and(|h| matches!(h.state, TaskState::Running { .. }))
    }

    /// Retrieve a snapshot of the current task state.
    pub async fn get_task(&self, task_id: &str) -> Option<BackgroundTask> {
        let map = lock_map(&self.tasks).await;
        map.get(task_id).map(|h| BackgroundTask {
            id: h.id.clone(),
            command: h.command.clone(),
            state: h.state.clone(),
            output_path: h.output_path.clone(),
        })
    }

    /// Mark a task as notified (dedup support for Step 1.3).
    pub async fn mark_notified(&self, task_id: &str) {
        let mut map = lock_map(&self.tasks).await;
        if let Some(h) = map.get_mut(task_id) {
            h.notified = true;
        }
    }

    /// Drain pending notifications without re-delivery.
    pub async fn pending_notifications(&self) -> Vec<CompletionNotification> {
        let mut n = self.notifications.lock().await;
        std::mem::take(&mut *n)
    }

    /// Remove output directories and handles for ALL terminal tasks
    /// belonging to the given session.
    /// Removes output for [`TaskState::Killed`] tasks.  Used during
    /// session purge to reclaim all output files for that session.
    pub async fn cleanup_all_finished(&self, session_id: &str) {
        let mut map = lock_map(&self.tasks).await;
        let finished: Vec<String> = map
            .iter()
            .filter(|(_, h)| {
                h.session_id == session_id
                    && matches!(
                        h.state,
                        TaskState::Completed { .. } | TaskState::Failed { .. } | TaskState::Killed
                    )
            })
            .map(|(id, _)| id.clone())
            .collect();

        for task_id in &finished {
            if let Some(handle) = map.get(task_id) {
                let parent = handle.output_path.parent();
                if let Some(dir) = parent {
                    if let Err(e) = tokio::fs::remove_dir_all(dir).await {
                        tracing::warn!(
                            task_id = %task_id,
                            path = %dir.display(),
                            error = %e,
                            "failed to remove task output directory"
                        );
                    }
                }
            }
            map.remove(task_id);
        }
    }
}

