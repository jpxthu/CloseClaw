#[async_trait::async_trait]
impl crate::TaskManager for BackgroundTaskManager {
    async fn spawn_task(
        &self,
        command: &str,
        cwd: &std::path::Path,
        is_backgrounded: bool,
        session_id: &str,
    ) -> Result<BackgroundTask, BackgroundTaskError> {
        self.spawn(command, cwd, is_backgrounded, session_id).await
    }

    async fn backgroundize_task(
        &self,
        child: tokio::process::Child,
        command: &str,
        is_backgrounded: bool,
        session_id: &str,
    ) -> Result<BackgroundTask, BackgroundTaskError> {
        self.backgroundize(child, command, is_backgrounded, session_id)
            .await
    }

    async fn kill_task(&self, task_id: &str) -> Result<(), BackgroundTaskError> {
        self.kill(task_id).await
    }

    async fn get_task(&self, task_id: &str) -> Option<BackgroundTask> {
        self.get_task(task_id).await
    }

    async fn list_running_tasks(&self) -> Vec<crate::task_manager::RunningTaskInfo> {
        let map = lock_map(&self.tasks).await;
        map.values()
            .filter(|h| matches!(h.state, TaskState::Running { .. }))
            .map(|h| crate::task_manager::RunningTaskInfo {
                task_id: h.id.clone(),
                command: h.command.clone(),
                elapsed_secs: h.created_at.elapsed().as_secs(),
            })
            .collect()
    }

    async fn drain_notifications(&self) -> Vec<CompletionNotification> {
        let mut notifications = self.pending_notifications().await;
        // Sort by priority descending: Now > Next > Later
        notifications.sort_by_key(|b| std::cmp::Reverse(b.priority));
        notifications
    }

    async fn cleanup_all_finished(&self, session_id: &str) {
        self.cleanup_all_finished(session_id).await
    }

    fn max_execution_secs(&self) -> u64 {
        self.max_execution_secs
    }
}

